CREATE TABLE LIQUIDACAO_PANINI
(
    ID                NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    ITEM_PEDIDO_ID    NUMBER NOT NULL,
    EDITORA           VARCHAR2(50) NOT NULL,
    TITULO            VARCHAR2(200) NOT NULL,
    FORMA_PAGAMENTO   VARCHAR2(30),
    QTD               NUMBER(10),
    PRECO_UNITARIO    NUMBER(12,2),
    VALOR_BRUTO       NUMBER(12,2),
    PERCENTUAL_LOJA   NUMBER(5,2),
    VALOR_LOJA        NUMBER(12,2),
    VALOR_EDITORA     NUMBER(12,2),
    STATUS_LIQUIDACAO VARCHAR2(30),
    DATA_VENDA        TIMESTAMP,
    DATA_LIQUIDACAO   TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT UK_LIQ_ITEM_PEDIDO UNIQUE (ITEM_PEDIDO_ID)
);