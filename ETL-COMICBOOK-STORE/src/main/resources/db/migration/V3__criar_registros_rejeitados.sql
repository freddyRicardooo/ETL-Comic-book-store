CREATE TABLE REGISTROS_REJEITADOS
(
    ID               NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    TIPO_REGISTRO    VARCHAR2(20) NOT NULL,
    LINHA_ARQUIVO    NUMBER,
    CONTEUDO         VARCHAR2(4000),
    MOTIVO           VARCHAR2(1000) NOT NULL,
    TIPO_EXCECAO     VARCHAR2(200),
    ETAPA            VARCHAR2(30),
    NOME_STEP        VARCHAR2(100),
    JOB_EXECUTION_ID NUMBER,
    DATA_REJEICAO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IDX_REJEITADOS_JOB_EXEC ON REGISTROS_REJEITADOS (JOB_EXECUTION_ID);