CREATE TABLE PEDIDO
(
    ID_PEDIDO       VARCHAR2(20 CHAR)  NOT NULL,
    DATA_HORA       TIMESTAMP NOT NULL,
    ID_CLIENTE      VARCHAR2(20 CHAR)  NOT NULL,
    NOME            VARCHAR2(100 CHAR) NOT NULL,
    EMAIL           VARCHAR2(150 CHAR) NOT NULL,
    STATUS          VARCHAR2(30 CHAR)  NOT NULL,
    FORMA_PAGAMENTO VARCHAR2(30 CHAR)  NOT NULL,
    VALOR_TOTAL     NUMBER(12,2)       NOT NULL,
    FRETE           NUMBER(10,2)       NOT NULL,
    DESCONTO        NUMBER(5,2)        NOT NULL,
    CONSTRAINT PK_PEDIDO PRIMARY KEY (ID_PEDIDO)
);

CREATE TABLE ITEM_PEDIDO
(
    ID             NUMBER(19,0) GENERATED ALWAYS AS IDENTITY,
    ID_PEDIDO      VARCHAR2(20 CHAR)  NOT NULL,
    SEQ            NUMBER(10,0)       NOT NULL,
    SKU            VARCHAR2(20 CHAR)  NOT NULL,
    TITULO         VARCHAR2(150 CHAR) NOT NULL,
    EDITORA        VARCHAR2(100 CHAR) NOT NULL,
    QTD            NUMBER(10,0)       NOT NULL,
    PRECO_UNITARIO NUMBER(10,2)       NOT NULL,
    VALOR_ITEM     NUMBER(12,2)       NOT NULL,
    CONSTRAINT PK_ITEM_PEDIDO PRIMARY KEY (ID),
    CONSTRAINT FK_ITEM_PEDIDO_PEDIDO FOREIGN KEY (ID_PEDIDO)
        REFERENCES PEDIDO (ID_PEDIDO)
);

CREATE INDEX IX_ITEM_PEDIDO_ID_PEDIDO ON ITEM_PEDIDO (ID_PEDIDO);