CREATE TABLE ARQUIVO_PROCESSADO
(
    ID               NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    HASH_ARQUIVO     VARCHAR2(64)  NOT NULL,
    NOME_ARQUIVO     VARCHAR2(255),
    TAMANHO_BYTES    NUMBER(19),
    STATUS           VARCHAR2(20)  NOT NULL,
    JOB_EXECUTION_ID NUMBER(19),
    DATA_INICIO      TIMESTAMP,
    DATA_FIM         TIMESTAMP,
    CONSTRAINT UK_ARQUIVO_HASH UNIQUE (HASH_SHA256),
    CONSTRAINT CK_ARQUIVO_STATUS CHECK (STATUS IN ('EM_PROCESSAMENTO', 'PROCESSADO', 'ERRO'))
);