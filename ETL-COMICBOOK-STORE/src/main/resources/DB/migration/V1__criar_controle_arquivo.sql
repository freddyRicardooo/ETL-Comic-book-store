CREATE TABLE CONTROLE_ARQUIVO
(
    ID               NUMBER(19,0) GENERATED ALWAYS AS IDENTITY,
    HASH_ARQUIVO     VARCHAR2(64 CHAR)   NOT NULL,
    NOME_ARQUIVO     VARCHAR2(255 CHAR)  NOT NULL,
    STATUS           VARCHAR2(20 CHAR)   NOT NULL,
    DATA_INICIO      TIMESTAMP NOT NULL,
    DATA_FIM         TIMESTAMP,
    MENSAGEM_ERRO    VARCHAR2(4000 CHAR),
    JOB_EXECUTION_ID NUMBER(19,0),
    CONSTRAINT PK_CONTROLE_ARQUIVO PRIMARY KEY (ID),
    CONSTRAINT UK_CONTROLE_ARQUIVO_HASH UNIQUE (HASH_ARQUIVO),
    CONSTRAINT CK_CONTROLE_ARQUIVO_STATUS
        CHECK (STATUS IN ('PROCESSANDO', 'PROCESSADO', 'ERRO'))
);